#!/usr/bin/env python3
"""Convert the title artwork into an indexed 240x180 pixel image for the game engine.

Usage: python3 tools/make_assets.py   (run from the mrs-anthrope-game folder)
Writes js/assets.js
"""
import base64
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "assets", "title_source.png")
OUT = os.path.join(ROOT, "js", "assets.js")


def main():
    im = Image.open(SRC).convert("RGB")
    small = im.resize((240, 180), Image.BOX)
    q = small.quantize(colors=32, method=Image.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[: 32 * 3]
    hexes = ["#%02x%02x%02x" % tuple(pal[i * 3 : i * 3 + 3]) for i in range(32)]
    data = base64.b64encode(q.tobytes()).decode("ascii")
    js = (
        "// generated by tools/make_assets.py - do not edit\n"
        "(function (root) {\n"
        "  var MA = root.MA = root.MA || {};\n"
        "  MA.ASSETS = { title: { w: 240, h: 180, pal: %s, data: %s } };\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n"
    ) % (json.dumps(hexes), json.dumps(data))
    with open(OUT, "w") as f:
        f.write(js)
    print("wrote", OUT, len(js), "bytes", file=sys.stderr)


if __name__ == "__main__":
    main()
